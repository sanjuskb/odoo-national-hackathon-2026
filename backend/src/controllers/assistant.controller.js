'use strict';

const { successResponse } = require('../utils/response');

async function handleChat(req, res, next) {
  const startTime = Date.now();
  try {
    const { message, context = {}, conversation_history = [] } = req.body || {};
    const text = (message || '').trim().toLowerCase();

    let reply = '';
    let intent = 'general_inquiry';

    if (text.includes('interval') || text.includes('frequency') || text.includes('frequencies') || text.includes('billing period')) {
      intent = 'billing_frequency';
      reply =
        'Brightloop supports four distinct recurring billing frequencies: Daily, Weekly, Monthly, and Yearly. Each subscription maintains an anchor date to prevent drift across month-ends or leap years, and invoices are generated automatically when a period matures.';
    } else if (text.includes('tax') || text.includes('discount') || text.includes('calculate') || text.includes('math')) {
      intent = 'pricing_and_financials';
      reply =
        'All financial figures in Brightloop are calculated server-side in exact integer minor units (paise) to eliminate floating-point anomalies. Line prices reflect base product prices plus variant adjustments, discounted with non-stackable caps, followed by precise jurisdictional tax line application (e.g., GST 18%).';
    } else if (text.includes('pause') || text.includes('renew') || text.includes('cancel') || text.includes('close')) {
      intent = 'lifecycle_policy';
      reply =
        'Subscriptions adhere strictly to plan permissions: if allow_pause is true, customers can pause active billing cycles. If allow_early_close is enabled, subscriptions can transition to closed early. Closed subscriptions become immutable ledgers and cannot be re-opened without creating a new quotation.';
    } else if (text.includes('invoice') || text.includes('payment') || text.includes('receipt') || text.includes('overdue')) {
      intent = 'invoices_and_payments';
      reply =
        'Invoices progress deterministically from Draft -> Confirmed -> Paid. Overdue status is computed dynamically when due_date has elapsed without full balance settlement. Partial payments reduce outstanding balance, and full settlement moves the invoice to Paid automatically.';
    } else if (text.includes('variant') || text.includes('odoo') || text.includes('product') || text.includes('560')) {
      intent = 'products_and_variants';
      reply =
        'Brightloop products can be configured with multiple variants (such as the standard Odoo ERP Variant at +560.00). When combined with the SaaS Base Platform at 1000.00, the resulting line item price is 1560.00 without double-counting.';
    } else if (text.includes('hello') || text.includes('hi') || text.includes('help')) {
      const name = context.full_name ? ` ${context.full_name}` : '';
      intent = 'greeting';
      reply = `Hello${name}! I am your Brightloop Customer Assistant. I can help explain subscription plans, recurring billing intervals, tax rules, or portal management. What would you like to explore today?`;
    } else {
      reply =
        `Thank you for your inquiry about "${message}". Brightloop is an end-to-end subscription management and billing system. You can browse active products and recurring plans in the catalog, transition quotations, and manage confirmed invoices with deterministic ledger reconciliation.`;
    }

    const latency_ms = Date.now() - startTime;

    return successResponse(
      res,
      200,
      {
        reply,
        intent,
        grounded: true,
        is_simulated: true,
        latency_ms,
        disclaimer: 'Brightloop AI Assistant provides advisory guidance; authoritative financial ledger amounts are generated by the server-side billing engine.',
        metadata: {
          customer_id: context.customer_id || null,
        },
      },
      'Assistant response generated'
    );
  } catch (err) {
    next(err);
  }
}

module.exports = {
  handleChat,
};

